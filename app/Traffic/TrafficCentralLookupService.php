/**
 * BAJAMA Central Traffic Lookup Engine V1
 *
 * Tujuan:
 * - membaca evidence dari traffic_observations
 * - mengidentifikasi provider/application/service
 * - memisahkan technical classification dari business category
 * - menghitung confidence
 * - menghasilkan knowledge object untuk traffic_lookup
 *
 * V1 BELUM menulis ke traffic_catalog.
 * V1 BELUM dipanggil oleh worker.
 *
 * Compatible dengan PHP 7.4+
 */
class TrafficCentralLookupService
{
    private PDO $db;

    public function __construct(PDO $db)
    {
        $this->db = $db;
    }

    /**
     * Lookup satu hostname berdasarkan evidence database.
     */
    public function lookupHostname(string $hostname): array
    {
        $hostname = $this->normalizeHostname($hostname);

        if ($hostname === null) {
            return [
                'success' => false,
                'hostname' => null,
                'error' => 'Hostname tidak valid.',
            ];
        }

        $evidence = $this->collectEvidence($hostname);
        $intelligence = $this->classifyHostname($hostname, $evidence);

        return [
            'success' => true,
            'hostname' => $hostname,
            'provider' => $intelligence['provider'],
            'application' => $intelligence['application'],
            'service' => $intelligence['service'],
            'technical_classification' => $intelligence['technical_classification'],
            'business_category' => $intelligence['business_category'],
            'confidence' => $intelligence['confidence'],
            'normalized_domain' => $intelligence['normalized_domain'],
            'evidence' => $evidence,
        ];
    }

    /**
     * Simpan hasil Central Lookup ke knowledge table.
     *
     * Method ini idempotent berdasarkan hostname_pattern.
     */
    public function persistResult(array $result): array
    {
        if (empty($result['success']) || empty($result['hostname'])) {
            throw new \InvalidArgumentException(
                'Hasil Central Lookup tidak valid.'
            );
        }

        $hostname = $this->normalizeHostname(
            (string)$result['hostname']
        );

        if ($hostname === null) {
            throw new \InvalidArgumentException(
                'Hostname hasil lookup tidak valid.'
            );
        }

        $categorySlug = strtolower(
            trim((string)($result['business_category'] ?? 'browser'))
        );

        if ($categorySlug === '') {
            $categorySlug = 'browser';
        }

        $categoryName = ucwords(
            str_replace(
                ['-', '_'],
                ' ',
                $categorySlug
            )
        );

        $categoryDescription =
            'Business category generated by BAJAMA Central Lookup.';

        /*
         * Central Lookup hanya membuat kategori baru jika
         * klasifikasi memang mempunyai identitas.
         *
         * Unknown tetap Browser / General.
         */
        $categoryId = $this->ensureLookupCategory(
            $categorySlug,
            $categoryName,
            $categoryDescription
        );

        $evidenceJson = json_encode(
            $result['evidence'] ?? [],
            JSON_UNESCAPED_SLASHES |
            JSON_UNESCAPED_UNICODE |
            JSON_PRETTY_PRINT
        );

        if ($evidenceJson === false) {
            $evidenceJson = '{}';
        }

        $sql = "
            INSERT INTO traffic_lookup (
                hostname_pattern,
                normalized_domain,
                provider,
                application,
                service,
                technical_classification,
                category_id,
                confidence,
                evidence,
                source_type,
                enabled,
                first_seen_at,
                last_seen_at
            )
            VALUES (
                :hostname_pattern,
                :normalized_domain,
                :provider,
                :application,
                :service,
                :technical_classification,
                :category_id,
                :confidence,
                :evidence,
                'CENTRAL_LOOKUP',
                1,
                COALESCE(
                    JSON_UNQUOTE(
                        JSON_EXTRACT(:evidence_first, '$.first_seen_at')
                    ),
                    NULL
                ),
                COALESCE(
                    JSON_UNQUOTE(
                        JSON_EXTRACT(:evidence_last, '$.last_seen_at')
                    ),
                    NULL
                )
            )
            ON DUPLICATE KEY UPDATE
                normalized_domain = VALUES(normalized_domain),
                provider = VALUES(provider),
                application = VALUES(application),
                service = VALUES(service),
                technical_classification =
                    VALUES(technical_classification),
                category_id = VALUES(category_id),
                confidence = VALUES(confidence),
                evidence = VALUES(evidence),
                enabled = 1,
                last_seen_at = VALUES(last_seen_at),
                updated_at = CURRENT_TIMESTAMP
        ";

        /*
         * Ambil first/last seen langsung dari evidence.
         */
        $evidence = $result['evidence'] ?? [];

        $firstSeen = $evidence['first_seen_at'] ?? null;
        $lastSeen = $evidence['last_seen_at'] ?? null;

        $stmt = $this->db->prepare($sql);

        $stmt->execute([
            ':hostname_pattern' =>
                $hostname,

            ':normalized_domain' =>
                (string)($result['normalized_domain'] ?? $hostname),

            ':provider' =>
                $result['provider'] ?? null,

            ':application' =>
                $result['application'] ?? null,

            ':service' =>
                $result['service'] ?? null,

            ':technical_classification' =>
                $result['technical_classification'] ?? null,

            ':category_id' =>
                $categoryId,

            ':confidence' =>
                (float)($result['confidence'] ?? 0),

            ':evidence' =>
                $evidenceJson,

            ':evidence_first' =>
                json_encode(
                    ['first_seen_at' => $firstSeen],
                    JSON_UNESCAPED_SLASHES
                ),

            ':evidence_last' =>
                json_encode(
                    ['last_seen_at' => $lastSeen],
                    JSON_UNESCAPED_SLASHES
                ),
        ]);

        $lookupStmt = $this->db->prepare("
            SELECT id
            FROM traffic_lookup
            WHERE hostname_pattern = :hostname
            LIMIT 1
        ");

        $lookupStmt->execute([
            ':hostname' => $hostname,
        ]);

        return [
            'id' => (int)$lookupStmt->fetchColumn(),
            'hostname' => $hostname,
            'category_id' => $categoryId,
            'category_slug' => $categorySlug,
        ];
    }

    /**
     * Pastikan kategori Central Lookup tersedia.
     */
    private function ensureLookupCategory(
        string $slug,
        string $name,
        string $description
    ): int {
        $slug = strtolower(trim($slug));

        $stmt = $this->db->prepare("
            SELECT id
            FROM traffic_categories
            WHERE slug = :slug
            LIMIT 1
        ");

        $stmt->execute([
            ':slug' => $slug,
        ]);

        $existing = $stmt->fetchColumn();

        if ($existing !== false) {
            return (int)$existing;
        }

        $sortStmt = $this->db->query("
            SELECT COALESCE(MAX(sort_order), 0)
            FROM traffic_categories
        ");

        $sortOrder = ((int)$sortStmt->fetchColumn()) + 10;

        $insert = $this->db->prepare("
            INSERT INTO traffic_categories (
                name,
                slug,
                description,
                icon,
                enabled,
                sort_order
            )
            VALUES (
                :name,
                :slug,
                :description,
                'bi-diagram-3',
                1,
                :sort_order
            )
        ");

        $insert->execute([
            ':name' => $name,
            ':slug' => $slug,
            ':description' => $description,
            ':sort_order' => $sortOrder,
        ]);

        return (int)$this->db->lastInsertId();
    }

    /**
     * Ambil hostname unik dari traffic observations.
     */
    public function listObservedHostnames(int $limit = 1000): array
    {
        $limit = max(1, min(10000, $limit));

        $sql = "
            SELECT
                LOWER(TRIM(hostname)) AS hostname,
                COUNT(*) AS observation_count
            FROM traffic_observations
            WHERE hostname IS NOT NULL
              AND TRIM(hostname) <> ''
            GROUP BY LOWER(TRIM(hostname))
            ORDER BY observation_count DESC, hostname ASC
            LIMIT {$limit}
        ";

        $stmt = $this->db->query($sql);

        $rows = $stmt->fetchAll(PDO::FETCH_ASSOC);

        $result = [];

        foreach ($rows as $row) {
            $hostname = $this->normalizeHostname(
                (string)($row['hostname'] ?? '')
            );

            if ($hostname === null) {
                continue;
            }

            $result[] = [
                'hostname' => $hostname,
                'observation_count' => (int)($row['observation_count'] ?? 0),
            ];
        }

        return $result;
    }

    /**
     * Ambil evidence runtime untuk satu hostname.
     */
    private function collectEvidence(string $hostname): array
    {
        $stmt = $this->db->prepare("
            SELECT
                COUNT(*) AS observation_count,

                COUNT(DISTINCT router_id) AS router_count,

                COUNT(DISTINCT organization_id) AS organization_count,

                COUNT(DISTINCT customer_ip) AS customer_count,

                COUNT(DISTINCT destination_ip) AS destination_count,

                GROUP_CONCAT(
                    DISTINCT destination_port
                    ORDER BY destination_port
                    SEPARATOR ','
                ) AS ports,

                GROUP_CONCAT(
                    DISTINCT UPPER(protocol)
                    ORDER BY UPPER(protocol)
                    SEPARATOR ','
                ) AS protocols,

                GROUP_CONCAT(
                    DISTINCT connection_mark
                    ORDER BY connection_mark
                    SEPARATOR ','
                ) AS connection_marks,

                GROUP_CONCAT(
                    DISTINCT packet_mark
                    ORDER BY packet_mark
                    SEPARATOR ','
                ) AS packet_marks,

                GROUP_CONCAT(
                    DISTINCT hostname_source
                    ORDER BY hostname_source
                    SEPARATOR ','
                ) AS hostname_sources,

                MIN(first_seen_at) AS first_seen_at,

                MAX(last_seen_at) AS last_seen_at,

                COALESCE(SUM(orig_bytes), 0) AS orig_bytes,

                COALESCE(SUM(repl_bytes), 0) AS repl_bytes,

                COALESCE(SUM(orig_packets), 0) AS orig_packets,

                COALESCE(SUM(repl_packets), 0) AS repl_packets

            FROM traffic_observations
            WHERE LOWER(TRIM(hostname)) = ?
        ");

        $stmt->execute([$hostname]);

        $row = $stmt->fetch(PDO::FETCH_ASSOC);

        if (!$row) {
            return [
                'observation_count' => 0,
                'router_count' => 0,
                'organization_count' => 0,
                'customer_count' => 0,
                'destination_count' => 0,
                'ports' => [],
                'protocols' => [],
                'connection_marks' => [],
                'packet_marks' => [],
                'hostname_sources' => [],
                'first_seen_at' => null,
                'last_seen_at' => null,
                'orig_bytes' => 0,
                'repl_bytes' => 0,
                'orig_packets' => 0,
                'repl_packets' => 0,
            ];
        }

        return [
            'observation_count' => (int)($row['observation_count'] ?? 0),
            'router_count' => (int)($row['router_count'] ?? 0),
            'organization_count' => (int)($row['organization_count'] ?? 0),
            'customer_count' => (int)($row['customer_count'] ?? 0),
            'destination_count' => (int)($row['destination_count'] ?? 0),

            'ports' => $this->csvToArray($row['ports'] ?? ''),
            'protocols' => $this->csvToArray($row['protocols'] ?? ''),
            'connection_marks' => $this->csvToArray(
                $row['connection_marks'] ?? ''
            ),
            'packet_marks' => $this->csvToArray(
                $row['packet_marks'] ?? ''
            ),
            'hostname_sources' => $this->csvToArray(
                $row['hostname_sources'] ?? ''
            ),

            'first_seen_at' => $row['first_seen_at'] ?? null,
            'last_seen_at' => $row['last_seen_at'] ?? null,

            'orig_bytes' => (int)($row['orig_bytes'] ?? 0),
            'repl_bytes' => (int)($row['repl_bytes'] ?? 0),
            'orig_packets' => (int)($row['orig_packets'] ?? 0),
            'repl_packets' => (int)($row['repl_packets'] ?? 0),
        ];
    }

