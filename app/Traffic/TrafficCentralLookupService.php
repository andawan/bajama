    /**
     * Build a normalized intelligence result.
     */
    private function buildResult(
        array $base,
        ?string $provider,
        ?string $application,
        ?string $service,
        string $technical,
        string $category,
        float $confidence,
        string $normalizedDomain
    ): array {
        $base['provider'] = $provider;
        $base['application'] = $application;
        $base['service'] = $service;
        $base['technical_classification'] = $technical;
        $base['business_category'] = $category;
        $base['confidence'] = min(100, max(0, $confidence));
        $base['normalized_domain'] = $normalizedDomain;

        return $base;
    }

    /**
     * Domain boundary matching.
     *
     * IMPORTANT:
     * xnxx.com MUST NOT match x.com.
     */
    private function domainMatches(
        string $hostname,
        string $domain
    ): bool {
        $hostname = strtolower(rtrim(trim($hostname), '.'));
        $domain = strtolower(rtrim(trim($domain), '.'));

        if ($hostname === '' || $domain === '') {
            return false;
        }

        return $hostname === $domain ||
            $this->endsWith($hostname, '.' . $domain);
    }

    private function containsToken(
        string $hostname,
        string $token
    ): bool {
        if ($token === '') {
            return false;
        }

        return strpos($hostname, $token) !== false;
    }

    /**
     * Domain-chain matching.
     *
     * Contoh:
     *   foo.tiktokv.com.bytewlb.akadns.net
     *   api.pangle.io.ttdns2.com
     *   foo.kwai-pro.com.akadns.net
     *
     * Berbeda dengan strpos(), pencocokan dilakukan pada
     * boundary domain sehingga tidak mudah menghasilkan
     * false-positive.
     */
    private function domainChainMatches(
        string $hostname,
        string $domain
    ): bool {
        $hostname = strtolower(rtrim(trim($hostname), '.'));
        $domain = strtolower(rtrim(trim($domain), '.'));

        if ($hostname === '' || $domain === '') {
            return false;
        }

        if ($this->domainMatches($hostname, $domain)) {
            return true;
        }

        return strpos($hostname, '.' . $domain . '.') !== false
            || strpos($hostname, '.' . $domain) !== false;
    }

    private function endsWith(
        string $haystack,
        string $needle
    ): bool {
        if ($needle === '') {
            return true;
        }

        return substr(
            $haystack,
            -strlen($needle)
        ) === $needle;
    }

    private function normalizeHostname(
        string $hostname
    ): ?string {
        $hostname = strtolower(trim($hostname));
        $hostname = rtrim($hostname, '.');

        if ($hostname === '') {
            return null;
        }

        if (strlen($hostname) > 253) {
            return null;
        }

        if (strpos($hostname, '.') === false) {
            return null;
        }

        if (filter_var($hostname, FILTER_VALIDATE_IP)) {
            return null;
        }

        if (strpos($hostname, '..') !== false) {
            return null;
        }

        if (
            !preg_match(
                '/^[a-z0-9][a-z0-9._-]*[a-z0-9]$/i',
                $hostname
            )
        ) {
            return null;
        }

        return $hostname;
    }

    private function csvToArray(string $value): array
    {
        if (trim($value) === '') {
            return [];
        }

        $parts = explode(',', $value);
        $result = [];

        foreach ($parts as $part) {
            $part = trim($part);

            if ($part !== '') {
                $result[] = $part;
            }
        }

        return array_values(array_unique($result));
    }

    private function knownDomainBase(
        string $hostname,
        string $domain
    ): string {
        /*
         * Direct domain:
         *   youtube.com
         *   shopee.co.id
         *   amazonaws.com
         *
         * Domain-chain:
         *   tiktokv.com.bytewlb.akadns.net
         *   kwai-pro.com.akadns.net
         *   pangle.io.ttdns2.com
         *
         * Jika domain aplikasi ditemukan di dalam chain,
         * gunakan domain tersebut sebagai normalized_domain,
         * bukan domain CDN/provider paling belakang.
         */
        if (
            $this->domainMatches($hostname, $domain)
            || $this->domainChainMatches($hostname, $domain)
        ) {
            return strtolower($domain);
        }

        return $this->parentDomain($hostname);
    }

    private function parentDomain(string $hostname): string
    {
        $parts = explode('.', strtolower($hostname));

        $count = count($parts);

        if ($count <= 2) {
            return $hostname;
        }

        return $parts[$count - 2] . '.' . $parts[$count - 1];
    }

    private function youtubeService(string $hostname): string
    {
        if (
            $this->domainMatches(
                $hostname,
                'googlevideo.com'
            )
        ) {
            return 'YouTube Video Delivery';
        }

        if (
            $this->domainMatches(
                $hostname,
                'ytimg.com'
            )
        ) {
            return 'YouTube Static Media';
        }

        if (
            $this->domainMatches(
                $hostname,
                'ggpht.com'
            )
        ) {
            return 'YouTube Image / Media';
        }

        return 'YouTube';
    }
